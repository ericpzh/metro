"""Replace the poster catalogue from a folder; fill standard canvases, strip metadata.

Usage: python tools/prep-posters.py C:/Users/ericp/Downloads/posters
Requires Pillow with WebP support. Outputs are deterministic and deduplicated.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'game/src/assets/posters'
SIZES = {'square': (384, 384), 'portrait': (288, 512), 'landscape': (512, 288)}


def main():
    source = Path(sys.argv[1]).resolve()
    assert source.is_dir() and source != TARGET.resolve()
    prepared, seen = [], set()
    for path in sorted(source.iterdir(), key=lambda p: p.name):
        if path.suffix.lower() not in {'.jpg', '.jpeg', '.jfif', '.png', '.webp'}:
            continue
        with Image.open(path) as original:
            image = ImageOps.exif_transpose(original).convert('RGB')
        ratio = image.width / image.height
        category = 'square' if .8 <= ratio <= 1.25 else 'portrait' if ratio < .8 else 'landscape'
        size = SIZES[category]
        canvas = ImageOps.fit(image, size, Image.Resampling.LANCZOS)
        digest = hashlib.sha256(canvas.tobytes()).hexdigest()
        if digest in seen:
            continue
        seen.add(digest)
        slug = category + '-' + re.sub(r'[^a-z0-9]+', '-', path.name.lower()).strip('-')
        shapes = ['landscape', 'wide', 'panorama'] if category == 'landscape' else [category]
        prepared.append((canvas, {'slug': slug, 'subject': path.name, 'shapes': shapes}))
    assert prepared, 'No readable posters; existing catalogue left intact'
    # Only remove files inside the verified repository asset directory.
    assert TARGET.resolve() == ROOT / 'game/src/assets/posters'
    TARGET.mkdir(parents=True, exist_ok=True)
    for path in TARGET.iterdir():
        if path.is_file():
            path.unlink()
    for canvas, entry in prepared:
        canvas.save(TARGET / (entry['slug'] + '.webp'), 'WEBP', quality=76, method=6)
    catalogue = '// Generated by tools/prep-posters.py; source filenames are authored content.\n'
    catalogue += "import type { AdPoster } from './billboards.ts'\n\n"
    catalogue += 'export const POSTER_CATALOGUE: readonly AdPoster[] = ' + json.dumps(
        [entry for _, entry in prepared], ensure_ascii=False, indent=2) + '\n'
    (ROOT / 'game/src/sim/posterCatalogue.ts').write_text(catalogue, encoding='utf-8')
    print(json.dumps({'posters': len(prepared), 'bytes': sum(p.stat().st_size for p in TARGET.iterdir())}))


if __name__ == '__main__':
    main()
