        void Awake() {
            Active = this;
            StationEditProfiling.Enabled = true;
            coordinator = new StationLoadCoordinator(transform) {
                Assets = new StationViewAssets { Catalogue = catalogue, TrainCatalogue = trainCatalogue, Shader = stationShader, Font = font },
            };
            foreach (var renderer in StationRenderers.Snapshot()) coordinator.RegisterRenderer(renderer);
            coordinator.SetSimulationHost(new StationSimulationHost());
            coordinator.Committed += OnCommitted;
            router = new StationCommandRouter(this);
            foreach (var handler in StationCommandHandlers.Snapshot()) {
                router.Register(handler);
                if (handler is IStationStateContributor contributor) RegisterStateContributor(contributor);
            }
            StationStatisticsFeature.Attach(this);
            RebuildDemoIndex();
        }

        void OnDestroy() {
            if (ReferenceEquals(Active, this)) Active = null;
            openInFlight = false;
            queuedBrowserCommands.Clear();
            ClearContributorCaches();
            Metro.App.Views.StationTvSchedule.ClearCache();
            StationPaintGame.Forget();
            FinishRenderTrace("host-destroyed");
            if (coordinator != null) {
                coordinator.Committed -= OnCommitted;
                coordinator.Dispose();
                coordinator = null;
            }
        }

        void OnEnable() {
            Active = this;
            // A scene reload in the editor starts with a fresh coordinator; nothing is
            // loaded until a command (or station.resync) arrives.
        }

        void Update() {
            if (coordinator == null) return;
            if (pendingRenderTrace != null && (tracedCamera == null || !tracedCamera.isActiveAndEnabled))
                FinishRenderTrace("no-render-camera");
            coordinator.Tick(Time.deltaTime);
            if (IsLoaded) TickFrameSinks();
            // A commit under a still pointer re-aims once, on this frame (plan 29 §3): the
            // release that caused it already paid its own scene pick, and a second pick inside
            // the commit path only lengthened the pause the player feels.
            if (hoverRefreshRequested) {
                hoverRefreshRequested = false;
                StationPointerRouter.RefreshHover(this);
            }
            if (clientSessionId.Length == 0 || openInFlight) return;
            stateTimer += Time.unscaledDeltaTime;
            if (stateTimer < Mathf.Max(0.02f, stateIntervalSeconds)) return;
            stateTimer = 0f;
            PublishStateNow();
        }

        /// <summary>
        /// Ask for one coalesced ghost re-aim after a commit, undo or redo (plan 29 §3). The
        /// next frame re-picks the cached pointer once; a burst of requests inside one frame
        /// still costs one pick.
        /// </summary>
        public void RequestHoverRefresh() => hoverRefreshRequested = true;

        /// <summary>True while a coalesced re-aim is waiting for the next frame (tests, diagnostics).</summary>
        public bool HoverRefreshPending => hoverRefreshRequested;

        internal void TickFrameSinksNow() {
            if (IsLoaded) TickFrameSinks();
        }

        void TickFrameSinks() {
            var sinks = StationFrameSinks.Snapshot();
            if (sinks.Count == 0) return;
            bool explodedOnly = StationExplodedView.IsStandaloneActive;
            var simulation = Simulation;
            double simTime = simulation?.SimTimeSeconds ?? 0;
            // The scheduler's fractional tick is a **presentation** input only: the
            // clock, service counts and train dispatch stay on whole ticks. A sink that
            // drives a family samples its last two tick frames at this fraction, so a
            // 1 Hz simulation renders as continuous motion instead of one-second steps
            // (RCA 14 §5.1).
            double fraction = simulation?.PresentationFraction ?? 0;
            if (double.IsNaN(fraction) || double.IsInfinity(fraction)) fraction = 0;
            var clock = new StationFrameClock(
                simulation?.SimulationTick ?? 0,
                simulation?.PresentationEpoch ?? 0,
                simTime,
                simTime - (1 - fraction) * StationSimConstants.SimSecondsPerTick,
                fraction,
                simulation?.Playing ?? false);
            for (int i = 0; i < sinks.Count; i++) {
                var sink = sinks[i];
                if (explodedOnly && !(sink is IStationActiveDuringExplodedView)) continue;
                try {
                    sink.Tick(Document, Index, clock);
                } catch (Exception error) {
                    Debug.LogException(error);
                }
            }
        }

        // --------------------------------------------------------------- transport

        /// <summary>The one JS → C# entry point: <c>SendMessage("StationGame", "BrowserCommand", json)</c>.</summary>
        public void BrowserCommand(string json) {
            if (router == null) return;
            if (openInFlight) {
                queuedBrowserCommands.Enqueue(json);
                return;
            }
            if (ShouldUseYieldedOpen() && isActiveAndEnabled && Application.isPlaying &&
                router.TryPrepareYieldedOpen(json, out var plan)) {
                openInFlight = true;
                StartCoroutine(RunYieldedOpen(plan));
                return;
            }
            ExecuteBrowserCommandNow(json);
        }

        void ExecuteBrowserCommandNow(string json) {
            if (PublishStreamed(writeChunk => router.TryStreamDirectReply(json, writeChunk))) {
                stateTimer = 0f;
                return;
            }
            var preTrace = StationEditProfiling.BeginBrowserCommand(CurrentRevision);
            var reply = router.Handle(json, out var trace, preTrace);
            if (pendingRenderTrace != null && pendingRenderTrace.Revision != CurrentRevision)
                FinishRenderTrace("superseded-before-render");
            if (trace != null) {
                stateTimer = 0f;
                StartRenderTrace(trace);
            }
            bool published = Publish(reply);
            trace?.Mark(published ? "commit-published" : "no-reply-transport");
        }

        bool PublishStreamed(Func<Action<string>, bool> stream) {
            if (ReplyPublished != null || !StationWebBridge.CanStream) return false;
            bool chunkFailed = false;
            bool streamed = stream(chunk => {
                if (!chunkFailed && !StationWebBridge.PublishChunk(chunk)) chunkFailed = true;
            });
            if (!streamed) return false;
            return !chunkFailed && StationWebBridge.FlushChunks();
        }

        System.Collections.IEnumerator RunYieldedOpen(StationCommandRouter.YieldedOpenPlan plan) {
            var command = plan.Command;
            var docJson = plan.DocumentJson;
            var source = plan.Source;
            var sourceId = plan.SourceId;
            plan = default;

            StationLoadResult result = null;
            var enumerator = coordinator.OpenYielded(docJson, source, sourceId, r => result = r);
            docJson = null;
            while (enumerator.MoveNext()) {
                yield return enumerator.Current;
            }
            if (router != null && result != null) {
                stateTimer = 0f;
                bool streamed = PublishStreamed(writeChunk => router.TryStreamCommitEnvelope(command, result, writeChunk));
                if (!streamed) {
                    string reply = router.FormatCommitOrReject(command, result);
                    Publish(reply);
                    reply = null;
                }
                result = null;
#if UNITY_WEBGL && !UNITY_EDITOR
                GC.Collect();
                yield return null;
#endif
            }
            openInFlight = false;
            while (!openInFlight && queuedBrowserCommands.Count > 0 && router != null) {
                string next = queuedBrowserCommands.Dequeue();
                if (ShouldUseYieldedOpen() && isActiveAndEnabled && Application.isPlaying &&
                    router.TryPrepareYieldedOpen(next, out var nextPlan)) {
                    openInFlight = true;
                    StartCoroutine(RunYieldedOpen(nextPlan));
                    yield break;
                }
                ExecuteBrowserCommandNow(next);
            }
        }

        void StartRenderTrace(StationEditProfiling.CommitTrace trace) {
            tracedCamera = StationEditScene.EditCamera(this);
            if (tracedCamera == null || !tracedCamera.isActiveAndEnabled) {
                tracedCamera = null;
                trace.Mark("no-render-camera");
                return;
            }
            pendingRenderTrace = trace;
            beganTracedRender = false;
            RenderPipelineManager.beginCameraRendering += BeginTracedCamera;
            RenderPipelineManager.endCameraRendering += EndTracedCamera;
        }

        void BeginTracedCamera(ScriptableRenderContext _, Camera camera) {
            if (camera != tracedCamera || pendingRenderTrace == null) return;
            if (pendingRenderTrace.Revision != CurrentRevision)
                FinishRenderTrace("superseded-before-render");
            else beganTracedRender = true;
        }

        void EndTracedCamera(ScriptableRenderContext _, Camera camera) {
            if (camera != tracedCamera || !beganTracedRender || pendingRenderTrace == null) return;
            var trace = pendingRenderTrace;
            bool matches = trace.Revision == CurrentRevision;
            FinishRenderTrace(matches ? "first-camera-render" : "superseded-before-render");
            if (matches && isActiveAndEnabled && Application.isPlaying) {
                StartCoroutine(MarkEndOfFramePresent(trace, trace.Revision));
            }
        }

        System.Collections.IEnumerator MarkEndOfFramePresent(StationEditProfiling.CommitTrace trace, int expectedRevision) {
            yield return new WaitForEndOfFrame();
            if (trace != null) {
                trace.Mark(CurrentRevision == expectedRevision ? "first-frame-presented" : "superseded-before-present");
            }
        }

        void FinishRenderTrace(string stage) {
            var trace = pendingRenderTrace;
            if (trace == null) return;
            pendingRenderTrace = null;
            tracedCamera = null;
            beganTracedRender = false;
            RenderPipelineManager.beginCameraRendering -= BeginTracedCamera;
            RenderPipelineManager.endCameraRendering -= EndTracedCamera;
            trace.Mark(stage);
        }

        /// <summary>
        /// One outbound player envelope to **both** transports: the WebGL bridge and
        /// the desktop/Editor presenter's <see cref="ReplyPublished"/> subscription.
        /// A family that publishes its own envelope (the sign face painter) must go
        /// through here: <see cref="StationWebBridge.Publish"/> is compiled out of the
        /// desktop player, so a direct call there could never reach the React painter
        /// (RCA 14 §4.1). Returns true when at least one transport was available.
        /// </summary>
        public bool PublishOutbound(string json) {
            if (string.IsNullOrEmpty(json)) return false;
            bool webgl = StationWebBridge.Publish(json);
            bool desktop = ReplyPublished != null;
            ReplyPublished?.Invoke(json);
            return webgl || desktop;
        }

        bool Publish(string json) => PublishOutbound(json);

        /// <summary>Send one coalesced state snapshot now (no document).</summary>
        public void PublishStateNow() {
            if (!IsLoaded) return;
            var statePayload = new JObject();
            MergeState(statePayload, useRawJsonCache: true);
            var reply = new JObject {
                ["schemaVersion"] = StationCommandRouter.SchemaVersion,
                ["kind"] = "state",
                ["id"] = "",
                ["sessionId"] = clientSessionId,
                ["revision"] = CurrentRevision,
                ["accepted"] = true,
                ["code"] = JValue.CreateNull(),
                ["payload"] = statePayload,
            };
            Publish(reply.ToString(Formatting.None));
        }

        /// <summary>
        /// One small, sequenced camera pose reply (plan 29 §5). The cube polls the rendered
        /// camera on every animation frame in the web reference; in the Unity player the pose
        /// therefore travels on its own frame-cadence message instead of waiting for the
        /// 100 ms general state interval. It carries no document, no revision and no view
        /// toggles, and it is dropped until the shell has registered its session.
        /// </summary>
        public void PublishCameraPose(JObject camera, long sequence) {
            if (camera == null || clientSessionId.Length == 0) return;
            var reply = new JObject {
                ["schemaVersion"] = StationCommandRouter.SchemaVersion,
                ["kind"] = "camera",
                ["id"] = "",
                ["sessionId"] = clientSessionId,
                ["revision"] = CurrentRevision,
                ["accepted"] = true,
                ["code"] = JValue.CreateNull(),
                ["payload"] = new JObject {
                    ["camera"] = camera,
                    ["sequence"] = sequence,
                },
            };
            Publish(reply.ToString(Formatting.None));
        }

        double nextAudioFrame;

        void LateUpdate() {
            if (!IsLoaded || openInFlight || clientSessionId.Length == 0) return;
            var session = (Simulation as StationSimulationHost)?.Session;
            var exploded = StationExplodedView.ActiveStandalone;
            var camera = exploded?.ViewerCamera ?? StationEditScene.EditCamera(this);
            if (session == null || camera == null) return;

            double now = Time.unscaledTimeAsDouble;
            if (now < nextAudioFrame) return;
            nextAudioFrame = now + (session.Playing && session.Speed > 1 ? 1.0 / 30 : .1);

            var position = StationCoordinates.WorldToDocument(camera.transform.position);
            var right = StationCoordinates.WorldToDocumentDirection(camera.transform.right);
            var trayPassengers = exploded?.Builder?.PresentedPassengers;
            var passengers = exploded == null ? session.PassengerFrames() : null;
            int count = trayPassengers?.Count ?? passengers?.Length ?? 0;
            int stride = Mathf.Max(1, Mathf.CeilToInt(count / 256f));
            var samples = new JArray();
            var sources = new JArray();
            for (int i = 0; i < count; i += stride) {
                if (trayPassengers != null) {
                    var passenger = trayPassengers[i];
                    samples.Add(passenger.X);
                    samples.Add(passenger.Y);
                    samples.Add(passenger.Z);
                } else {
                    var passenger = passengers[i];
                    if (!passenger.Visible) continue;
                    samples.Add(passenger.X);
                    samples.Add(passenger.Y);
                    samples.Add(passenger.Z);
                }
            }
            var trains = exploded != null ? exploded.Builder?.PresentedConsists : TrainConsistRenderer.Current?.Consists;
            Vector3 nearest = default;
            float best = float.PositiveInfinity;
            if (session.Playing && trains != null) {
                foreach (var train in trains) {
                    if (train.Phase == TrainPhase.None || train.Root == null || !train.Root.activeInHierarchy) continue;
                    var point = StationCoordinates.WorldToDocument(train.Root.transform.position);
                    float distance = (point - position).sqrMagnitude;
                    if (distance < best) { nearest = point; best = distance; }
                }
            }
            if (best < float.PositiveInfinity) sources.Add(AudioSourcePayload("train", nearest, .65));
            var vehicles = exploded == null ? StationRoadRenderer.Current?.Vehicles?.Poses : null;
            best = float.PositiveInfinity;
            if (vehicles != null) {
                for (int i = 0; i < Mathf.Min(64, vehicles.Count); i++) {
                    var vehicle = vehicles[i];
                    var point = new Vector3((float)vehicle.X, (float)vehicle.Y, (float)vehicle.Z);
                    float distance = (point - position).sqrMagnitude;
                    if (distance < best) { nearest = point; best = distance; }
                }
            }
            if (best < float.PositiveInfinity) sources.Add(AudioSourcePayload("traffic", nearest, .4));
            PublishAudio(new JObject {
                ["position"] = AudioPoint(position), ["right"] = AudioPoint(right),
                ["sources"] = sources, ["passengers"] = samples,
                ["sampleWeight"] = stride, ["speed"] = session.Speed,
            });
        }

        static JArray AudioPoint(Vector3 point) => new JArray(point.x, point.y, point.z);

        static JObject AudioSourcePayload(string kind, Vector3 position, double level) =>
            new JObject { ["kind"] = kind, ["position"] = AudioPoint(position), ["level"] = level };

        internal void PublishAudio(JObject payload) {
            if (clientSessionId.Length == 0) return;
            var reply = new JObject {
                ["schemaVersion"] = StationCommandRouter.SchemaVersion,
                ["kind"] = "audio",
                ["sessionId"] = clientSessionId,
                ["payload"] = payload,
            };
            Publish(reply.ToString(Formatting.None));
        }

