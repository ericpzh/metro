        void OnCommitted(StationCommitInfo info) {
            cameraBounds = info.CameraBounds;
            // A document edit re-installs the same station: keep the player's storey and
            // framing. Only a New/Open/demo commit opens at the document's lowest authored
            // metre and frames the fresh bounds (plan 11 D4).
            if (!editingDocument) {
                stationEpoch++;
                ResetAudioGateState();
                ClearContributorCaches();
                Metro.App.Views.StationTvSchedule.ClearCache();
                StationPaintGame.Forget();
                StationCellTool.ForgetWorld();
                StationZoneTool.ForgetWorld();
                StationPointerRouter.CancelActiveGesture(this, StationEditHost.Ensure());
                StationEditSession.ClearSelection();
                StationEditSession.ClearHistory();
                activeLevel = info.Document == null ? 0 : info.Document.OpeningLevel;
                if (frameCameraOnCommit && stationCamera != null && !info.CameraBounds.IsEmpty) FrameCamera(info.CameraBounds);
                if (Application.isPlaying && !Application.isBatchMode) {
                    StationScenePicker.WarmUp(coordinator?.World);
                    StationCellTool.WarmUp(this);
                    StationEditHost.Ensure().EnsureBound(this);
                }
            } else if (StationEditSession.HasCarried && !StationEditSession.HasPointer && !StationPointerRouter.CommittingMove) {
                StationPointerRouter.RevalidateParkedMove(this, StationEditHost.Ensure(), out _, out _);
            }
            // The commit reply is published by StationCommandRouter for the command that
            // caused it. Publishing a second, unsolicited commit here would make the
            // shell parse the same document twice.
        }

        void FrameCamera(StationCameraBounds bounds) {
            var centre = bounds.Centre;
            var distance = Mathf.Max(30f, bounds.Radius * 2.2f);
            var offset = new Vector3(distance * 0.72f, distance * 0.82f, -distance * 0.72f);
            stationCamera.transform.position = centre + offset;
            stationCamera.transform.LookAt(centre);
            stationCamera.orthographic = true;
            stationCamera.orthographicSize = bounds.OrthoSize;
            stationCamera.farClipPlane = Mathf.Max(360f, distance * 4f + bounds.Radius * 4f);
        }

