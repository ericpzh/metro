        public StationLoadResult NewStation(JObject payload) {
            var name = payload?["name"] != null ? (string)payload["name"] : "未命名车站";
            var city = payload?["city"] != null ? (string)payload["city"] : "guangzhou";
            long seed = 1234567;
            if (payload?["seed"] != null) {
                try { seed = (long)payload["seed"]; } catch (Exception) { seed = 1234567; }
            }
            return coordinator.New(name, city, seed);
        }

        public StationLoadResult OpenDocument(string json, string sourceId) =>
            coordinator.Open(json, new StationSource(sourceId == "file" ? "" : sourceId, ""), sourceId);

        internal bool TryResolveDemoInput(string id, out string text, out StationSource source) {
            if (string.IsNullOrEmpty(id) || !demoDocuments.TryGetValue(id, out var document) || document == null) {
                text = null;
                source = StationSource.None;
                return false;
            }
            text = document.text;
            source = new StationSource("demo:" + id, "");
            return true;
        }

        public StationLoadResult OpenDemo(string id) {
            if (string.IsNullOrEmpty(id) || !demoDocuments.TryGetValue(id, out var document) || document == null) {
                return StationLoadResult.Rejected(new StationRejection("unknown-demo", StationRecordKind.Document,
                    "demo", id ?? "", "No demo document named '" + id + "' is serialized in this scene."), CurrentRevision);
            }
            return coordinator.Open(document.text, new StationSource("demo:" + id, ""), id);
        }

        /// <summary>Republish the current commit; boot a New station when nothing is loaded.</summary>
        public StationLoadResult Resync() {
            if (!IsLoaded) return coordinator.New("未命名车站", "guangzhou", 1234567);
            return new StationLoadResult {
                Accepted = true,
                Revision = CurrentRevision,
                Document = Document,
                Index = Index,
                CameraBounds = cameraBounds,
                Diagnostics = Array.Empty<StationDiagnostic>(),
            };
        }

        public bool ApplySimCommand(string type, JObject payload, out string rejectCode) {
            if (Simulation is IStationSimulationCommands commands) {
                bool accepted = commands.ApplySimCommand(type, payload, out rejectCode);
                if (accepted) {
                    StationViewFeature.Active?.SyncSky();
                    stateTimer = Mathf.Max(stateTimer, stateIntervalSeconds);
                }
                return accepted;
            }
            rejectCode = "no-session";
            return false;
        }

        public string SaveDocument() => coordinator?.Save(DateTimeOffset.UtcNow) ?? "";

        /// <summary>
        /// The committed normalized envelope text as it already stands — no re-serialization, no
        /// re-parse. It is what the local edit path puts on the history stack in place of a fresh
        /// <see cref="SaveDocument"/> frame (plan 30 §3).
        /// </summary>
        public string CommittedDocumentJson => Document?.NormalizedJson ?? "";

        /// <summary>
        /// Try the **local** edit path for one cell patch (plan 30 §3): the next document and
        /// index are built from the committed read result plus the patch, then installed through
        /// the same transaction as an open. Returns null when the patch is outside the local
        /// whitelist, and the caller falls back to <see cref="ApplyDocumentEdit"/> with a complete
        /// envelope; the resulting document, revision and undo frame are the same either way.
        /// </summary>
        public StationLoadResult TryApplyLocalCells(StationCellPatch patch, string sourceId, out string code) {
            code = null;
            if (!IsLoaded) { code = "no-session"; return null; }
            StationLoadResult result;
            editingDocument = true;
            try {
                result = coordinator.TryInstallLocalCellEdit(patch, string.IsNullOrEmpty(sourceId) ? CurrentSourceId : sourceId, out code);
            } finally {
                editingDocument = false;
            }
            return result;
        }

        /// <summary>Try the local edit path for one module add/replace/remove (plan 30 §3).</summary>
        public StationLoadResult TryApplyLocalModule(StationModuleEditMode mode, StationEditDraft draft,
            string removeId, string sourceId, out string code) {
            code = null;
            if (!IsLoaded) { code = "no-session"; return null; }
            StationLoadResult result;
            editingDocument = true;
            try {
                result = coordinator.TryInstallLocalModuleEdit(mode, draft, removeId,
                    string.IsNullOrEmpty(sourceId) ? CurrentSourceId : sourceId, out code);
            } finally {
                editingDocument = false;
