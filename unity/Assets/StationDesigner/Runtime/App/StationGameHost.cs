        public StationLoadResult OpenDocument(string json, string sourceId) =>
            coordinator.Open(json, new StationSource(sourceId == "file" ? "" : sourceId, ""), sourceId);

        public StationLoadResult OpenDemo(string id) {
            if (string.IsNullOrEmpty(id) || !demoDocuments.TryGetValue(id, out var document) || document == null) {
                return StationLoadResult.Rejected(new StationRejection("unknown-demo", StationRecordKind.Document,
                    "demo", id ?? "", "No demo document named '" + id + "' is serialized in this scene."), CurrentRevision);
            }
            return coordinator.Open(document.text, new StationSource("demo:" + id, ""), id);
        }

        /// <summary>Republish the current commit; boot a New station when nothing is loaded.</summary>
        public StationLoadResult Resync() {
            if (!IsLoaded) return coordinator.New("Ã¦Å“ÂªÃ¥â€˜Â½Ã¥ÂÂÃ¨Â½Â¦Ã§Â«â„¢", "guangzhou", 1234567);
            return new StationLoadResult {
                Accepted = true,
                Revision = CurrentRevision,
                Document = Document,
                Index = Index,
                CameraBounds = cameraBounds,
                Diagnostics = Array.Empty<StationDiagnostic>(),
            };
        }

        public bool ApplySimCommand(string type, JObject payload, out string rejectCode) {
            if (Simulation is IStationSimulationCommands commands) {
                bool accepted = commands.ApplySimCommand(type, payload, out rejectCode);
                if (accepted) stateTimer = Mathf.Max(stateTimer, stateIntervalSeconds);
                return accepted;
            }
            rejectCode = "no-session";
            return false;
        }

        public string SaveDocument() => coordinator?.Save(DateTimeOffset.UtcNow) ?? "";

        /// <summary>
        /// The edit transaction a feature handler calls: hand it the complete normalized
        /// v1 document text. It installs through the same atomic transaction as an open,
        /// bumps the revision once, and the router replies with the commit for the
        /// command that caused it. The router has already checked `expectedRevision`.
        /// </summary>
        public StationLoadResult ApplyDocumentEdit(string json, string sourceId) {
            if (!IsLoaded) return StationLoadResult.Rejected(new StationRejection("no-session", StationRecordKind.Document,
                "station", "", "No station is committed, so there is nothing to edit."), CurrentRevision);
            // An edit is the same station, not a station switch: the commit must not re-home
            // the camera or move the player to another storey. The candidate was resolved at
            // the current level, and a fixed screen pixel has to keep aiming at the piece it
            // placed (plan 16 §1.5, and the source keeps the view for ordinary edits).
            editingDocument = true;
            try {
                return coordinator.InstallEditedDocument(json, string.IsNullOrEmpty(sourceId) ? CurrentSourceId : sourceId);
            } finally {
                editingDocument = false;
            }
        }

        /// <summary>The committed state as a load result, for a handler-triggered commit reply.</summary>
        public StationLoadResult CurrentResult() => IsLoaded
            ? new StationLoadResult {
                Accepted = true, Revision = CurrentRevision, Document = Document, Index = Index,
                CameraBounds = cameraBounds, Diagnostics = Array.Empty<StationDiagnostic>(),
            }
            : StationLoadResult.Rejected(new StationRejection("no-session", StationRecordKind.Document, "station", "",
                "No station is committed."), CurrentRevision);

        // ------------------------------------------------------------- snapshots

        public JObject BuildCommitPayload() {
            var payload = new JObject {
                ["document"] = Document?.NormalizedJson ?? "",
                ["documentRevision"] = CurrentRevision,
                ["sourceId"] = CurrentSourceId,
                ["sourceHash"] = CurrentSourceHash,
                ["capabilities"] = router.BuildCapabilities(),
            };
            MergeState(payload);
            return payload;
        }

        public JObject BuildStatePayload() {
            var payload = new JObject();
            MergeState(payload);
            return payload;
        }

        void MergeState(JObject payload) {
            payload["level"] = activeLevel;
            payload["name"] = Document?.Name ?? "";
            payload["speed"] = Simulation?.Speed ?? 1;
            payload["playing"] = Simulation?.Playing ?? false;
            // A6: the committed tool rides the same state frame as the camera, so the
            // rail can settle on the host's answer rather than its own click.
            payload["tool"] = StationToolSelection.Active;
            payload["toolGeneration"] = StationToolSelection.Generation;
            // C3: the committed session's own service counts. Nobody is queued or
            // boarded when there is no session, so the empty case is still zero.
            var serviceHost = Simulation as StationSimulationHost;
            var service = serviceHost != null ? serviceHost.Session?.Services : null;
            payload["queued"] = service != null ? service.QueueTotal : 0;
            payload["boarded"] = service != null ? service.Onboard : 0;
            var clock = SafeObject(Simulation?.ClockPayloadJson());
            if (clock != null) payload["clock"] = clock;
            // The clock's sibling: the transports this session honours. A shell that
            // offers Play/speed must read both from the same frame, because a clock
            // alone cannot say whether the host can honour the action (plan 13 §1).
            var simulationCapabilities = SafeObject(Simulation?.CapabilitiesPayloadJson());
            if (simulationCapabilities != null) payload["simulationCapabilities"] = simulationCapabilities;
            for (int i = 0; i < contributors.Count; i++) {
                try {
                    var value = contributors[i].BuildPayload(Document, Index);
                    if (value != null) payload[contributors[i].Key] = value;
                } catch (Exception error) {
                    payload[contributors[i].Key] = new JObject { ["error"] = error.Message };
                }
            }
            if (payload["camera"] == null && stationCamera != null) payload["camera"] = BuildCameraTransformPayload();
        }

        /// <summary>
        /// The current scene camera in document axes. Packet D registers a `camera`
        /// contributor with the orbit target and projection it really drives; this
        /// fallback only reports the transform of the baseline camera.
        /// </summary>
        JObject BuildCameraTransformPayload() {
            var transform = stationCamera.transform;
            var position = StationCoordinates.WorldToDocument(transform.position);
            var forward = StationCoordinates.WorldToDocumentDirection(transform.forward);
            var right = StationCoordinates.WorldToDocumentDirection(transform.right);
            var up = StationCoordinates.WorldToDocumentDirection(transform.up);
            return new JObject {
                ["position"] = Vector(position),
                ["target"] = Vector(position + forward),
                ["right"] = Vector(right),
                ["up"] = Vector(up),
                ["back"] = Vector(-forward),
                ["fov"] = stationCamera.fieldOfView,
                ["ortho"] = stationCamera.orthographic,
                ["level"] = activeLevel,
                ["orthoSize"] = stationCamera.orthographicSize,
                ["distance"] = Vector3.Distance(transform.position, cameraBounds.Centre),
                ["source"] = "camera-transform",
            };
        }

        static JObject Vector(Vector3 value) => new JObject { ["x"] = value.x, ["y"] = value.y, ["z"] = value.z };

        static JObject SafeObject(string json) {
            if (string.IsNullOrEmpty(json)) return null;
            try { return JObject.Parse(json); } catch (JsonException) { return null; }
        }

        // ------------------------------------------------------------- commit hook

        void OnCommitted(StationCommitInfo info) {
            cameraBounds = info.CameraBounds;
            // A document edit re-installs the same station: keep the player's storey and
            // framing. Only a New/Open/demo commit opens at the document's lowest authored
            // metre and frames the fresh bounds (plan 11 D4).
            if (!editingDocument) {
                activeLevel = info.Document == null ? 0 : info.Document.OpeningLevel;
                if (frameCameraOnCommit && stationCamera != null && !info.CameraBounds.IsEmpty) FrameCamera(info.CameraBounds);
            }
            // The commit reply is published by StationCommandRouter for the command that
            // caused it. Publishing a second, unsolicited commit here would make the
            // shell parse the same document twice.
        }

        void FrameCamera(StationCameraBounds bounds) {
            var centre = bounds.Centre;
            var distance = Mathf.Max(30f, bounds.Radius * 2.2f);
            var offset = new Vector3(distance * 0.72f, distance * 0.82f, -distance * 0.72f);
            stationCamera.transform.position = centre + offset;
            stationCamera.transform.LookAt(centre);
            stationCamera.orthographic = true;
            stationCamera.orthographicSize = bounds.OrthoSize;
            stationCamera.farClipPlane = Mathf.Max(360f, distance * 4f + bounds.Radius * 4f);
        }

        // ---------------------------------------------------------- demo manifest

        void RebuildDemoIndex() {
            demoDocuments.Clear();
            if (demos != null) {
                foreach (var demo in demos) {
                    if (demo == null || string.IsNullOrEmpty(demo.id) || demo.document == null) continue;
                    demoDocuments[demo.id] = demo.document;
                }
            }
        }

        /// <summary>The demo ids this scene can open, in manifest order.</summary>
        public IReadOnlyList<string> DemoIds {
            get {
                var ids = new List<string>(demoDocuments.Count);
                if (demos != null) {
                    foreach (var demo in demos) if (demo != null && demoDocuments.ContainsKey(demo.id)) ids.Add(demo.id);
                }
                return ids;
            }
        }

        /// <summary>Wrap a command path for tests: returns the reply and whether it committed.</summary>
        public string SendForTest(string json) => router == null ? "" : router.Handle(json);
    }

    /// <summary>The WebGL transport: one JS function, one DOM event.</summary>
    public static class StationWebBridge {
#if UNITY_WEBGL && !UNITY_EDITOR
        [DllImport("__Internal")]
        static extern void StationGameState(string json);
#endif
        /// <summary>
        /// Send one envelope to the WebGL page. Returns false when this build has no
        /// WebGL transport at all (the desktop/Editor player), so a caller can tell
        /// "delivered" from "this platform has no such route" instead of assuming.
        /// </summary>
        public static bool Publish(string json) {
#if UNITY_WEBGL && !UNITY_EDITOR
            try { StationGameState(json); return true; } catch (Exception) { return false; /* a missing glue function must not crash the player */ }
#else
            return false;
#endif
        }
    }
