    /// <summary>
    /// The generic station player: one scene component on a GameObject named exactly
    /// <c>StationGame</c>, one command path in (<see cref="BrowserCommand"/>) and one
    /// snapshot path out (<c>metro:station-state</c> through the WebGL bridge).
    ///
    /// It owns the committed document, its revision and the install transaction
    /// (<see cref="StationLoadCoordinator"/>): New, file Open, demo Open and cold
    /// resync all pass through the same reader Ã¢â€ â€™ index Ã¢â€ â€™ staged world/session Ã¢â€ â€™
    /// commit path. Camera/view/sign/road/material packets register renderers,
    /// command handlers and state contributors; nothing here knows a station id or
    /// an authored layout.
    /// </summary>
    [AddComponentMenu("Metro/Station Game Host")]
    public sealed class StationGameHost : MonoBehaviour {
        public const string ObjectName = "StationGame";

        [Serializable]
        public sealed class DemoStation {
            public string id = "";
            public TextAsset document;
        }

        [Header("Assets (serialized by path in Scenes/StationGame.unity)")]
        public RuntimeCatalogue catalogue;
        public TrainCatalogue trainCatalogue;
        public Shader stationShader;
        public Font font;

        [Header("Demos (no authored station root; the manifest is generated by A1)")]
        public TextAsset demoManifest;
        public DemoStation[] demos = Array.Empty<DemoStation>();

        [Header("Baseline camera (packet D replaces the controls, not the bounds)")]
        public Camera stationCamera;
        public bool frameCameraOnCommit = true;

        [Header("Snapshots")]
        [Tooltip("Real seconds between coalesced state replies. Commits are immediate.")]
        public float stateIntervalSeconds = 0.1f;

        StationLoadCoordinator coordinator;
        StationCommandRouter router;
        readonly List<IStationStateContributor> contributors = new List<IStationStateContributor>();
        readonly Dictionary<string, TextAsset> demoDocuments = new Dictionary<string, TextAsset>(StringComparer.Ordinal);
        StationCameraBounds cameraBounds;
        int activeLevel;
        float stateTimer;
        string clientSessionId = "";
        /// <summary>True while <see cref="ApplyDocumentEdit"/> installs an edit of the committed station.</summary>
        bool editingDocument;

        /// <summary>Every reply this host publishes, for EditMode/PlayMode tests.</summary>
        public event Action<string> ReplyPublished;

        public StationLoadCoordinator Coordinator => coordinator;
        public StationCommandRouter Router => router;
        public StationIndex Index => coordinator?.Index;
        public StationDocument Document => coordinator?.Document;
        public bool IsLoaded => coordinator != null && coordinator.IsLoaded;
        public int CurrentRevision => coordinator?.Revision ?? 0;
        public string CurrentSourceId => coordinator?.SourceId ?? "";
        public string CurrentSourceHash => coordinator?.SourceHash ?? "";
        public IStationSimulationHost Simulation => coordinator?.Simulation;
        public StationCameraBounds CameraBounds => cameraBounds;
        public int ActiveLevel => activeLevel;
        public int DemoCount => demoDocuments.Count;
        public string ClientSessionId => clientSessionId;
        public IReadOnlyList<IStationStateContributor> Contributors => contributors;

        void Awake() {
            coordinator = new StationLoadCoordinator(transform) {
                Assets = new StationViewAssets { Catalogue = catalogue, TrainCatalogue = trainCatalogue, Shader = stationShader, Font = font },
            };
            foreach (var renderer in StationRenderers.Snapshot()) coordinator.RegisterRenderer(renderer);
            coordinator.SetSimulationHost(new StationSimulationHost());
            coordinator.Committed += OnCommitted;
            router = new StationCommandRouter(this);
            foreach (var handler in StationCommandHandlers.Snapshot()) router.Register(handler);
            StationStatisticsFeature.Attach(this);
            RebuildDemoIndex();
        }

        void OnDestroy() {
            if (coordinator != null) {
                coordinator.Committed -= OnCommitted;
                coordinator.Dispose();
                coordinator = null;
            }
        }

        void OnEnable() {
            // A scene reload in the editor starts with a fresh coordinator; nothing is
            // loaded until a command (or station.resync) arrives.
        }

        void Update() {
            if (coordinator == null) return;
            coordinator.Tick(Time.deltaTime);
            if (IsLoaded) TickFrameSinks();
            if (clientSessionId.Length == 0) return;
            stateTimer += Time.unscaledDeltaTime;
            if (stateTimer < Mathf.Max(0.02f, stateIntervalSeconds)) return;
            stateTimer = 0f;
            PublishStateNow();
        }

        void TickFrameSinks() {
            var sinks = StationFrameSinks.Snapshot();
            if (sinks.Count == 0) return;
            var simulation = Simulation;
            double simTime = simulation?.SimTimeSeconds ?? 0;
            // The scheduler's fractional tick is a **presentation** input only: the
            // clock, service counts and train dispatch stay on whole ticks. A sink that
            // drives a family samples its last two tick frames at this fraction, so a
            // 1 Hz simulation renders as continuous motion instead of one-second steps
            // (RCA 14 §5.1).
            double fraction = simulation?.PresentationFraction ?? 0;
            if (double.IsNaN(fraction) || double.IsInfinity(fraction)) fraction = 0;
            var clock = new StationFrameClock(
                simulation?.SimulationTick ?? 0,
                simulation?.PresentationEpoch ?? 0,
                simTime,
                simTime - (1 - fraction) * StationSimConstants.SimSecondsPerTick,
                fraction,
                simulation?.Playing ?? false);
            for (int i = 0; i < sinks.Count; i++) {
                try {
                    sinks[i].Tick(Document, Index, clock);
                } catch (Exception error) {
                    Debug.LogException(error);
                }
            }
        }

        // --------------------------------------------------------------- transport

        /// <summary>The one JS Ã¢â€ â€™ C# entry point: <c>SendMessage("StationGame", "BrowserCommand", json)</c>.</summary>
        public void BrowserCommand(string json) {
            if (router == null) return;
            Publish(router.Handle(json));
        }

        /// <summary>
        /// One outbound player envelope to **both** transports: the WebGL bridge and
        /// the desktop/Editor presenter's <see cref="ReplyPublished"/> subscription.
        /// A family that publishes its own envelope (the sign face painter) must go
        /// through here: <see cref="StationWebBridge.Publish"/> is compiled out of the
        /// desktop player, so a direct call there could never reach the React painter
        /// (RCA 14 §4.1). Returns true when at least one transport was available.
        /// </summary>
        public bool PublishOutbound(string json) {
            if (string.IsNullOrEmpty(json)) return false;
            bool webgl = StationWebBridge.Publish(json);
            bool desktop = ReplyPublished != null;
            ReplyPublished?.Invoke(json);
            return webgl || desktop;
        }

        bool Publish(string json) => PublishOutbound(json);

        /// <summary>Send one coalesced state snapshot now (no document).</summary>
        public void PublishStateNow() {
            if (!IsLoaded) return;
            var reply = new JObject {
                ["schemaVersion"] = StationCommandRouter.SchemaVersion,
                ["kind"] = "state",
                ["id"] = "",
                ["sessionId"] = clientSessionId,
                ["revision"] = CurrentRevision,
                ["accepted"] = true,
                ["code"] = JValue.CreateNull(),
                ["payload"] = BuildStatePayload(),
            };
            Publish(reply.ToString(Formatting.None));
        }

        public void NoteClientSession(string sessionId) {
            if (!string.IsNullOrEmpty(sessionId)) clientSessionId = sessionId;
        }

        // ------------------------------------------------------------- registration

        public void RegisterRenderer(IStationViewRenderer renderer) {
            if (coordinator == null) throw new InvalidOperationException("Station host is not initialised.");
            coordinator.RegisterRenderer(renderer);
        }

        public bool UnregisterRenderer(string role) => coordinator != null && coordinator.UnregisterRenderer(role);

        public void SetSimulationHost(IStationSimulationHost simulation) => coordinator.SetSimulationHost(simulation);

        public void RegisterStateContributor(IStationStateContributor contributor) {
            if (contributor == null) throw new ArgumentNullException(nameof(contributor));
            for (int i = contributors.Count - 1; i >= 0; i--) {
                if (string.Equals(contributors[i].Key, contributor.Key, StringComparison.Ordinal)) contributors.RemoveAt(i);
            }
            contributors.Add(contributor);
        }

        public bool UnregisterStateContributor(string key) {
            for (int i = contributors.Count - 1; i >= 0; i--) {
                if (string.Equals(contributors[i].Key, key, StringComparison.Ordinal)) { contributors.RemoveAt(i); return true; }
            }
            return false;
        }

        public void RegisterCommandHandler(IStationCommandHandler handler) => router.Register(handler);

        public bool UnregisterCommandHandler(string capability) => router.Unregister(capability);

        /// <summary>Packet D publishes the active view level; it is not part of the document.</summary>
        public void SetActiveLevel(int level) => activeLevel = level;

