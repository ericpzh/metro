        }

        /// <summary>Try the local edit path for patching one exit module's demand/open/name settings.</summary>
        public StationLoadResult TryApplyLocalExitSettings(string moduleId, bool hasName, string name,
            bool hasInRate, double inRate, bool hasOpen, bool open, string sourceId, out string code) {
            code = null;
            if (!IsLoaded) { code = "no-session"; return null; }
            StationLoadResult result;
            editingDocument = true;
            try {
                result = coordinator.TryInstallLocalExitSettings(moduleId, hasName, name, hasInRate, inRate,
                    hasOpen, open, string.IsNullOrEmpty(sourceId) ? CurrentSourceId : sourceId, out code);
            } finally {
                editingDocument = false;
            }
            return result;
        }

        /// <summary>
        /// The edit transaction a feature handler calls: hand it the complete normalized
        /// v1 document text. It installs through the same atomic transaction as an open,
        /// bumps the revision once, and the router replies with the commit for the
        /// command that caused it. The router has already checked `expectedRevision`.
        /// </summary>
        public StationLoadResult ApplyDocumentEdit(string json, string sourceId) {
            if (!IsLoaded) return StationLoadResult.Rejected(new StationRejection("no-session", StationRecordKind.Document,
                "station", "", "No station is committed, so there is nothing to edit."), CurrentRevision);
            // An edit is the same station, not a station switch: the commit must not re-home
            // the camera or move the player to another storey. The candidate was resolved at
            // the current level, and a fixed screen pixel has to keep aiming at the piece it
            // placed (plan 16 §1.5, and the source keeps the view for ordinary edits).
            editingDocument = true;
            try {
                return coordinator.InstallEditedDocument(json, string.IsNullOrEmpty(sourceId) ? CurrentSourceId : sourceId);
            } finally {
                editingDocument = false;
            }
        }

        /// <summary>The committed state as a load result, for a handler-triggered commit reply.</summary>
        public StationLoadResult CurrentResult() => IsLoaded
            ? new StationLoadResult {
                Accepted = true, Revision = CurrentRevision, Document = Document, Index = Index,
                CameraBounds = cameraBounds, Diagnostics = Array.Empty<StationDiagnostic>(),
