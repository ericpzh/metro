            }
        }

        void MergeState(JObject payload, bool useRawJsonCache = false) {
            payload["level"] = activeLevel;
            payload["name"] = Document?.Name ?? "";
            payload["speed"] = Simulation?.Speed ?? 1;
            payload["playing"] = Simulation?.Playing ?? false;
            // A6: the committed tool rides the same state frame as the camera, so the
            // rail can settle on the host's answer rather than its own click.
            payload["tool"] = StationToolSelection.Active;
            payload["toolGeneration"] = StationToolSelection.Generation;
            // Plan 27 §2: what the secondary mouse button means for the committed tool, so the
            // shell's camera adapter can leave a claimed tool gesture alone instead of starting a
            // pan. It travels on the state frame because an ack payload never reaches the shell's
            // shared store.
            payload["rightClaim"] = StationToolSelection.RightClaim;
            payload["settingsGeneration"] = StationToolSelection.SettingsGeneration;
            // C3: the committed session's own service counts. Nobody is queued or
            // boarded when there is no session, so the empty case is still zero.
            var serviceHost = Simulation as StationSimulationHost;
            var liveSession = serviceHost != null ? serviceHost.Session : null;
            var service = liveSession?.Services;
            payload["queued"] = service != null ? service.QueueTotal : 0;
            payload["boarded"] = service != null ? service.Onboard : 0;
            var clockJson = Simulation?.ClockPayloadJson();
            if (!string.IsNullOrEmpty(clockJson)) {
                if (useRawJsonCache) payload["clock"] = new JRaw(clockJson);
                else { var clock = SafeObject(clockJson); if (clock != null) payload["clock"] = clock; }
            }
            // The clock's sibling: the transports this session honours. A shell that
            // offers Play/speed must read both from the same frame, because a clock
            // alone cannot say whether the host can honour the action (plan 13 §1).
            var simCapsJson = Simulation?.CapabilitiesPayloadJson();
            if (!string.IsNullOrEmpty(simCapsJson)) {
                if (useRawJsonCache) payload["simulationCapabilities"] = new JRaw(simCapsJson);
                else { var simulationCapabilities = SafeObject(simCapsJson); if (simulationCapabilities != null) payload["simulationCapabilities"] = simulationCapabilities; }
            }
            for (int i = 0; i < contributors.Count; i++) {
                string key = contributors[i].Key;
                try {
                    if (useRawJsonCache && TryWriteCachedContributorRaw(key, payload, liveSession)) continue;
                    var value = contributors[i].BuildPayload(Document, Index);
                    if (value != null) {
                        if (useRawJsonCache) {
                            UpdateContributorRawCache(key, value, liveSession);
                            if (TryWriteCachedContributorRaw(key, payload, liveSession)) continue;
                        }
                        payload[key] = value;
                    }
                } catch (Exception error) {
                    payload[key] = new JObject { ["error"] = error.Message };
                }
            }
            if (payload["camera"] == null && stationCamera != null) payload["camera"] = BuildCameraTransformPayload();
        }

        /// <summary>
        /// The current scene camera in document axes. Packet D registers a `camera`
        /// contributor with the orbit target and projection it really drives; this
        /// fallback only reports the transform of the baseline camera.
        /// </summary>
        JObject BuildCameraTransformPayload() {
            var transform = stationCamera.transform;
            var position = StationCoordinates.WorldToDocument(transform.position);
            var forward = StationCoordinates.WorldToDocumentDirection(transform.forward);
            var right = StationCoordinates.WorldToDocumentDirection(transform.right);
            var up = StationCoordinates.WorldToDocumentDirection(transform.up);
            return new JObject {
                ["position"] = Vector(position),
                ["target"] = Vector(position + forward),
                ["right"] = Vector(right),
                ["up"] = Vector(up),
                ["back"] = Vector(-forward),
                ["fov"] = stationCamera.fieldOfView,
                ["ortho"] = stationCamera.orthographic,
                ["level"] = activeLevel,
                ["orthoSize"] = stationCamera.orthographicSize,
                ["distance"] = Vector3.Distance(transform.position, cameraBounds.Centre),
                ["source"] = "camera-transform",
            };
        }

        static JObject Vector(Vector3 value) => new JObject { ["x"] = value.x, ["y"] = value.y, ["z"] = value.z };

        static JObject SafeObject(string json) {
            if (string.IsNullOrEmpty(json)) return null;
            try { return JObject.Parse(json); } catch (JsonException) { return null; }
        }

