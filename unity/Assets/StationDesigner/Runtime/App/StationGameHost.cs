        public void RegisterStateContributor(IStationStateContributor contributor) {
            if (contributor == null) throw new ArgumentNullException(nameof(contributor));
            for (int i = contributors.Count - 1; i >= 0; i--) {
                if (string.Equals(contributors[i].Key, contributor.Key, StringComparison.Ordinal)) contributors.RemoveAt(i);
            }
            contributors.Add(contributor);
        }

        public bool UnregisterStateContributor(string key) {
            for (int i = contributors.Count - 1; i >= 0; i--) {
                if (string.Equals(contributors[i].Key, key, StringComparison.Ordinal)) { contributors.RemoveAt(i); return true; }
            }
            return false;
        }

