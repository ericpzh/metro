        void Awake() {
            Active = this;
            StationEditProfiling.Enabled = true;
            coordinator = new StationLoadCoordinator(transform) {
                Assets = new StationViewAssets { Catalogue = catalogue, TrainCatalogue = trainCatalogue, Shader = stationShader, Font = font },
            };
            foreach (var renderer in StationRenderers.Snapshot()) coordinator.RegisterRenderer(renderer);
            coordinator.SetSimulationHost(new StationSimulationHost());
            coordinator.Committed += OnCommitted;
            router = new StationCommandRouter(this);
            foreach (var handler in StationCommandHandlers.Snapshot()) {
                router.Register(handler);
                if (handler is IStationStateContributor contributor) RegisterStateContributor(contributor);
            }
            StationStatisticsFeature.Attach(this);
            RebuildDemoIndex();
        }

        void OnDestroy() {
            if (ReferenceEquals(Active, this)) Active = null;
            openInFlight = false;
            queuedBrowserCommands.Clear();
            ResetAudioGateState();
            ClearContributorCaches();
            Metro.App.Views.StationTvSchedule.ClearCache();
            Metro.App.Views.StationTvPlatePainter.DisposePool();
            StationPaintGame.Forget();
            FinishRenderTrace("host-destroyed");
            if (coordinator != null) {
                coordinator.Committed -= OnCommitted;
                coordinator.Dispose();
                coordinator = null;
            }
        }

        static bool desktopPipelineTuned;

        static void ConfigureDesktopRenderPipeline() {
#if !UNITY_WEBGL
            if (desktopPipelineTuned || !Application.isPlaying || Application.isEditor) return;
            desktopPipelineTuned = true;
            try {
                var rp = UnityEngine.Rendering.GraphicsSettings.currentRenderPipeline;
                if (rp == null) return;
                var t = rp.GetType();
                t.GetProperty("supportsCameraDepthTexture")?.SetValue(rp, false);
                t.GetProperty("supportsCameraOpaqueTexture")?.SetValue(rp, false);
                // StationRenderRig sets LightShadows.None on all scene lights; zero shadowDistance
                // so URP skips shadow-map setup and shadow caster culling on desktop standalone.
                t.GetProperty("shadowDistance")?.SetValue(rp, 0f);
                t.GetProperty("shadowCascadeCount")?.SetValue(rp, 1);
                // Disable ScreenSpaceAmbientOcclusion at runtime on standalone desktop so URP skips
                // the full-scene DepthNormals prepass over 19k+ static renderers without altering
                // serialized URP assets or triggering shader variant recompilation.
                var rendererDataListField = t.GetField("m_RendererDataList",
                    System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic);
                if (rendererDataListField?.GetValue(rp) is System.Array rendererList) {
                    for (int i = 0; i < rendererList.Length; i++) {
                        var rd = rendererList.GetValue(i);
                        if (rd == null) continue;
                        var featuresProp = rd.GetType().GetProperty("rendererFeatures");
                        if (featuresProp?.GetValue(rd) is System.Collections.IEnumerable features) {
                            foreach (var feature in features) {
                                if (feature == null) continue;
                                if (feature.GetType().Name.IndexOf("AmbientOcclusion", StringComparison.OrdinalIgnoreCase) >= 0) {
                                    feature.GetType().GetMethod("SetActive", new[] { typeof(bool) })
                                        ?.Invoke(feature, new object[] { false });
                                }
                            }
                        }
                    }
                }
            } catch { /* ignore on non-URP pipelines */ }
#endif
        }

        void OnEnable() {
            Active = this;
