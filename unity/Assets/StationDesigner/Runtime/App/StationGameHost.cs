        void RebuildDemoIndex() {
            demoDocuments.Clear();
            if (demos != null) {
                foreach (var demo in demos) {
                    if (demo == null || string.IsNullOrEmpty(demo.id) || demo.document == null) continue;
                    demoDocuments[demo.id] = demo.document;
                }
            }
        }

        /// <summary>The demo ids this scene can open, in manifest order.</summary>
        public IReadOnlyList<string> DemoIds {
            get {
                var ids = new List<string>(demoDocuments.Count);
                if (demos != null) {
                    foreach (var demo in demos) if (demo != null && demoDocuments.ContainsKey(demo.id)) ids.Add(demo.id);
                }
                return ids;
            }
        }

