        static bool TryMeasureModuleDocumentBounds(StationWorldView world, string moduleId, out StationBox box) {
            box = default;
            if (world == null || string.IsNullOrEmpty(moduleId)) return false;
            bool any = false;
            var min = new Vector3(float.MaxValue, float.MaxValue, float.MaxValue);
            var max = new Vector3(float.MinValue, float.MinValue, float.MinValue);

            void EncapsulateWorldPoint(Vector3 wp) {
                var dp = StationCoordinates.WorldToDocument(wp);
                min = Vector3.Min(min, dp);
                max = Vector3.Max(max, dp);
                any = true;
            }

            void EncapsulateMesh(Mesh mesh, Matrix4x4 matrix) {
                if (mesh == null) return;
                if (mesh.isReadable && mesh.vertexCount > 0) {
                    var verts = mesh.vertices;
                    for (int i = 0; i < verts.Length; i++) {
                        EncapsulateWorldPoint(matrix.MultiplyPoint3x4(verts[i]));
                    }
                    return;
                }
                var b = mesh.bounds;
                if (b.size == Vector3.zero && mesh.vertexCount == 0) return;
                for (int c = 0; c < 8; c++) {
                    var lp = new Vector3(
                        (c & 1) == 0 ? b.min.x : b.max.x,
                        (c & 2) == 0 ? b.min.y : b.max.y,
                        (c & 4) == 0 ? b.min.z : b.max.z);
                    EncapsulateWorldPoint(matrix.MultiplyPoint3x4(lp));
                }
            }

            foreach (var record in world.Records) {
                if (record?.View == null) continue;
                if (string.Equals(record.ModuleId, moduleId, StringComparison.Ordinal)) {
                    foreach (var filter in record.View.GetComponentsInChildren<MeshFilter>(true)) {
                        if (filter == null || filter.sharedMesh == null) continue;
                        if (!filter.gameObject.activeInHierarchy) continue;
                        var mr = filter.GetComponent<MeshRenderer>();
                        if (mr != null && !mr.enabled) continue;
                        EncapsulateMesh(filter.sharedMesh, filter.transform.localToWorldMatrix);
                    }
                    continue;
                }
                if (record.SourceIds != null && record.SourceIds.Length > 0) {
                    int srcIdx = Array.IndexOf(record.SourceIds, moduleId);
                    if (srcIdx < 0) continue;
                    if (record.View.TryGetComponent<StationInstancedSurfaceBatch>(out var batch) &&
                        batch.SharedMesh != null &&
                        batch.TryGetSourceRange(srcIdx, out int start, out int count)) {
                        for (int k = 0; k < count; k++) {
                            EncapsulateMesh(batch.SharedMesh, batch.Matrices[start + k]);
                        }
                    } else if (record.SourceBounds != null && srcIdx < record.SourceBounds.Length &&
                               !record.SourceBounds[srcIdx].IsEmpty) {
                        var sb = record.SourceBounds[srcIdx];
                        min = Vector3.Min(min, new Vector3((float)sb.X0, (float)sb.Y0, (float)sb.Z0));
                        max = Vector3.Max(max, new Vector3((float)sb.X1, (float)sb.Y1, (float)sb.Z1));
                        any = true;
                    }
                }
            }

            if (!any) return false;
            box = new StationBox(min.x, min.y, min.z, max.x, max.y, max.z);
            return true;
        }

        static bool TryMeasurePreviewDocumentBounds(StationPlacementPreview preview, out StationBox box, out bool anyPlainBox) {
            box = default;
            anyPlainBox = false;
            if (preview == null) return false;
            bool any = false;
            var min = new Vector3(float.MaxValue, float.MaxValue, float.MaxValue);
            var max = new Vector3(float.MinValue, float.MinValue, float.MinValue);

            foreach (var filter in preview.GetComponentsInChildren<MeshFilter>(false)) {
                if (filter == null || filter.sharedMesh == null) continue;
                var mr = filter.GetComponent<MeshRenderer>();
                if (mr == null || !mr.enabled) continue;
                if (filter.gameObject.name == "selection box" || filter.gameObject.name == "erase surface batch") continue;
                var mesh = filter.sharedMesh;
                if (mesh.subMeshCount == 0 || mesh.GetTopology(0) != MeshTopology.Triangles) continue;
                if (filter.gameObject.name == "preview box") anyPlainBox = true;
                var matrix = filter.transform.localToWorldMatrix;
                if (mesh.isReadable && mesh.vertexCount > 0) {
                    var verts = mesh.vertices;
                    for (int i = 0; i < verts.Length; i++) {
                        var dp = StationCoordinates.WorldToDocument(matrix.MultiplyPoint3x4(verts[i]));
                        min = Vector3.Min(min, dp);
                        max = Vector3.Max(max, dp);
                        any = true;
                    }
                } else {
                    var b = mesh.bounds;
                    for (int c = 0; c < 8; c++) {
                        var lp = new Vector3(
                            (c & 1) == 0 ? b.min.x : b.max.x,
                            (c & 2) == 0 ? b.min.y : b.max.y,
                            (c & 4) == 0 ? b.min.z : b.max.z);
                        var dp = StationCoordinates.WorldToDocument(matrix.MultiplyPoint3x4(lp));
                        min = Vector3.Min(min, dp);
                        max = Vector3.Max(max, dp);
                        any = true;
                    }
                }
            }

            if (!any) return false;
            box = new StationBox(min.x, min.y, min.z, max.x, max.y, max.z);
            return true;
        }

        static Vector3 ReadVec3(JToken tok) => new Vector3((float)tok[0], (float)tok[1], (float)tok[2]);

        static float MaxAbs(Vector3 v) => Mathf.Max(Mathf.Abs(v.x), Mathf.Max(Mathf.Abs(v.y), Mathf.Abs(v.z)));

        static string Fmt(Vector3 v) =>
            $"({v.x.ToString("0.###", CultureInfo.InvariantCulture)},{v.y.ToString("0.###", CultureInfo.InvariantCulture)},{v.z.ToString("0.###", CultureInfo.InvariantCulture)})";

        /// <summary>
        /// Compute the max bounds delta against Web Three.js, honouring the one documented
        /// intentional non-position geometry difference: Unity's <see cref="StationRoadView"/>
        /// draws 3D side curbs (bottom at <c>z + 0.90</c>) whereas Web's <c>RoadModel.ts</c>
        /// draws a flat <c>PlaneGeometry</c> at <c>z + 1.025</c>. Road XY footprint and top Z
        /// are still strictly verified within <paramref name="tolerance"/>.
        /// </summary>
        static float EffectiveBoundsError(string type, Vector3 uMin, Vector3 uMax, Vector3 webMin, Vector3 webMax, float tolerance) {
            var dMin = uMin - webMin;
            var dMax = uMax - webMax;
            if (string.Equals(type, "road", StringComparison.Ordinal) && dMin.z >= -0.14f && dMin.z <= tolerance) {
                dMin.z = 0f;
            }
            return Mathf.Max(MaxAbs(dMin), MaxAbs(dMax));
        }

        [Test]
        public void AuditAllCatalogueAndContextualPlacementAgainstWebOracle() {
            Assert.IsTrue(File.Exists(OraclePath), "Missing oracle: " + OraclePath);
            var oracle = JObject.Parse(File.ReadAllText(OraclePath));
            var cases = (JArray)oracle["cases"];
            Assert.IsNotNull(cases);

            var sb = new StringBuilder();
            sb.AppendLine("=== CATALOGUE & CONTEXTUAL PLACEMENT AUDIT (" + cases.Count + " cases) ===");

            var mismatches = new List<(string CaseId, string Group, string Type, float Err, string Detail)>();
            var missing = new List<string>();
            int checkedCount = 0;

            bool prevIgnoreLogs = LogAssert.ignoreFailingMessages;
            if (SystemInfo.graphicsDeviceType == GraphicsDeviceType.Null) LogAssert.ignoreFailingMessages = true;
            var hostRoot = new GameObject("PlacementAuditRoot");
            try {
                for (int i = 0; i < cases.Count; i++) {
                    var c = (JObject)cases[i];
                    var caseId = (string)c["caseId"];
                    var group = (string)c["group"];
                    var targetId = (string)c["targetId"];
                    var modules = (JArray)c["modules"];
                    var cells = (JArray)c["cells"];
                    var lines = (JArray)c["lines"];
                    var web = (JObject)c["web"];
                    var webMin = ReadVec3(web["min"]);
                    var webMax = ReadVec3(web["max"]);
                    var webCenter = ReadVec3(web["center"]);
                    var webSize = ReadVec3(web["size"]);

                    var saveJson = BuildSaveJson(cells, modules, lines);
                    var read = StationDocumentReader.Read(saveJson, StationSource.None);
                    var targetMod = read.Index.GetModule(targetId);
                    var targetType = targetMod?.Type ?? "?";

                    var renderers = ProductionRenderers();
                    var world = new StationWorldView(hostRoot.transform, "case-" + i, renderers, Assets());
                    try {
                        world.Build(read.Document, read.Index);
                        world.Activate();
                        checkedCount++;

                        if (!TryMeasureModuleDocumentBounds(world, targetId, out var uBox)) {
                            missing.Add($"{caseId} ({targetType}): no rendered geometry found in Unity");
                            continue;
                        }

                        var uMin = new Vector3((float)uBox.X0, (float)uBox.Y0, (float)uBox.Z0);
                        var uMax = new Vector3((float)uBox.X1, (float)uBox.Y1, (float)uBox.Z1);
                        var uCenter = (uMin + uMax) * 0.5f;
                        var uSize = uMax - uMin;

                        var dCenter = uCenter - webCenter;
                        var dSize = uSize - webSize;
                        float maxErr = EffectiveBoundsError(targetType, uMin, uMax, webMin, webMax, 0.02f);

                        if (maxErr > 0.02f) {
                            string detail =
                                $"dCenter={Fmt(dCenter)} dSize={Fmt(dSize)} " +
                                $"web=[{Fmt(webMin)}..{Fmt(webMax)}] unity=[{Fmt(uMin)}..{Fmt(uMax)}]";
                            mismatches.Add((caseId, group, targetType, maxErr, detail));
                        }
                    } finally {
                        world.Dispose();
                    }
                }
            } finally {
                UnityEngine.Object.DestroyImmediate(hostRoot);
                StationRenderers.Clear();
                StationFrameSinks.Clear();
                LogAssert.ignoreFailingMessages = prevIgnoreLogs;
            }

            sb.AppendLine($"Checked: {checkedCount}, Missing: {missing.Count}, Mismatches (>0.02m): {mismatches.Count}");
            if (missing.Count > 0) {
                sb.AppendLine("\n--- MISSING GEOMETRY ---");
                foreach (var m in missing) sb.AppendLine("  " + m);
            }
            if (mismatches.Count > 0) {
                sb.AppendLine("\n--- MISMATCHES (grouped by group + type + base case) ---");
                foreach (var m in mismatches.OrderByDescending(x => x.Err).ThenBy(x => x.CaseId, StringComparer.Ordinal)) {
                    sb.AppendLine($"  [{m.Group}] {m.CaseId} ({m.Type}) maxErr={m.Err.ToString("0.###", CultureInfo.InvariantCulture)}m | {m.Detail}");
                }
            }

            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(AuditReportPath)));
            File.WriteAllText(AuditReportPath, sb.ToString());
            Debug.Log($"PLACEMENT_AUDIT_DONE checked={checkedCount} missing={missing.Count} mismatches={mismatches.Count} report={Path.GetFullPath(AuditReportPath)}");

            if (missing.Count > 0 || mismatches.Count > 0) {
                Assert.Fail($"Placement audit found {missing.Count} missing and {mismatches.Count} mismatches (see {Path.GetFullPath(AuditReportPath)}).\nFirst 30:\n" +
                    string.Join("\n", mismatches.Take(30).Select(m => $"{m.CaseId}: {m.Detail}")));
            }
        }

        [Test]
        public void AuditAllShippedDemosPlacementAgainstWebOracle() {
            if (!File.Exists(DemoOraclePath)) {
                Assert.Ignore("Demo oracle not present at " + Path.GetFullPath(DemoOraclePath));
                return;
            }
            var demoOracle = JObject.Parse(File.ReadAllText(DemoOraclePath));
            var demos = (JArray)demoOracle["demos"];

            var sb = new StringBuilder();
            sb.AppendLine("\n=== SHIPPED DEMOS PLACEMENT AUDIT ===");
            int totalMismatches = 0;
            int totalChecked = 0;

            bool prevIgnoreLogs = LogAssert.ignoreFailingMessages;
            if (SystemInfo.graphicsDeviceType == GraphicsDeviceType.Null) LogAssert.ignoreFailingMessages = true;
            var hostRoot = new GameObject("DemoPlacementAuditRoot");
            try {
                foreach (JObject demoObj in demos) {
                    var demoName = (string)demoObj["demo"];
                    var demoPath = $"Assets/StationDesigner/Demos/{demoName}.metro.json";
                    var read = StationDocumentReader.ReadFile(demoPath);
                    var renderers = ProductionRenderers();
                    var world = new StationWorldView(hostRoot.transform, "demo-" + demoName, renderers, Assets());
                    try {
                        world.Build(read.Document, read.Index);
                        world.Activate();

                        var items = (JArray)demoObj["items"];
                        var byGroup = new Dictionary<string, List<(string Id, int Rot, float Err, Vector3 DCenter, Vector3 DSize)>>(StringComparer.Ordinal);
                        int mismatchCount = 0;

                        foreach (JObject item in items) {
                            var id = (string)item["id"];
                            var type = (string)item["type"];
                            var variant = (string)item["variant"];
                            var rot = (int)item["rot"];
                            var webMin = ReadVec3(item["min"]);
                            var webMax = ReadVec3(item["max"]);
                            var webCenter = ReadVec3(item["center"]);
                            var webSize = ReadVec3(item["size"]);
                            totalChecked++;

                            if (!TryMeasureModuleDocumentBounds(world, id, out var uBox)) {
                                // Deliberate no-view (e.g. second half of tv pair or hidden outdoor surface tile)
                                continue;
                            }
                            var uMin = new Vector3((float)uBox.X0, (float)uBox.Y0, (float)uBox.Z0);
                            var uMax = new Vector3((float)uBox.X1, (float)uBox.Y1, (float)uBox.Z1);
                            var uCenter = (uMin + uMax) * 0.5f;
                            var uSize = uMax - uMin;
                            var dCenter = uCenter - webCenter;
                            var dSize = uSize - webSize;
                            float err = EffectiveBoundsError(type, uMin, uMax, webMin, webMax, 0.05f);
                            if (err > 0.05f) {
                                mismatchCount++;
                                totalMismatches++;
                                string gKey = $"{type}:{variant}";
                                if (!byGroup.TryGetValue(gKey, out var list)) byGroup[gKey] = list = new List<(string, int, float, Vector3, Vector3)>();
                                list.Add((id, rot, err, dCenter, dSize));
                            }
                        }

                        sb.AppendLine($"\nDemo `{demoName}`: checked={items.Count} mismatches(>0.05m)={mismatchCount}");
                        foreach (var kv in byGroup.OrderByDescending(k => k.Value.Max(x => x.Err))) {
                            var worst = kv.Value.OrderByDescending(x => x.Err).First();
                            sb.AppendLine($"  {kv.Key,-32} count={kv.Value.Count,5} worst={worst.Err.ToString("0.###", CultureInfo.InvariantCulture)}m " +
                                $"sample={worst.Id} r={worst.Rot} dCenter={Fmt(worst.DCenter)} dSize={Fmt(worst.DSize)}");
                        }
                    } finally {
                        world.Dispose();
                    }
                }
            } finally {
                UnityEngine.Object.DestroyImmediate(hostRoot);
                StationRenderers.Clear();
                StationFrameSinks.Clear();
                LogAssert.ignoreFailingMessages = prevIgnoreLogs;
            }

            File.AppendAllText(AuditReportPath, sb.ToString());
            Debug.Log($"DEMO_PLACEMENT_AUDIT_DONE checked={totalChecked} mismatches={totalMismatches}");
            if (totalMismatches > 0) {
                Assert.Fail($"Demo placement audit found {totalMismatches} mismatches across demos.\n" + sb.ToString());
            }
        }

