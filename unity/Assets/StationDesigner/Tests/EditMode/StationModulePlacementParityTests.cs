            for (int i = 0; i < 4; i++) {
                modules.Add(new JObject { ["id"] = $"tree-on-{i}", ["type"] = "tree", ["x"] = i * 2, ["y"] = 2, ["z"] = 0, ["rot"] = 0, ["cfg"] = new JObject() });
                modules.Add(new JObject { ["id"] = $"tree-off-{i}", ["type"] = "tree", ["x"] = i * 2, ["y"] = 6, ["z"] = 0, ["rot"] = 0, ["cfg"] = new JObject() });
                modules.Add(new JObject { ["id"] = $"bench-on-{i}", ["type"] = "bench", ["x"] = i * 2 + 1, ["y"] = 2, ["z"] = 0, ["rot"] = 0, ["w"] = 1, ["cfg"] = new JObject { ["variant"] = "steel-1" } });
                modules.Add(new JObject { ["id"] = $"bench-off-{i}", ["type"] = "bench", ["x"] = i * 2 + 1, ["y"] = 6, ["z"] = 0, ["rot"] = 0, ["w"] = 1, ["cfg"] = new JObject { ["variant"] = "steel-1" } });
            }

            // Targets at y = 10 (initially NO sidewalk) to verify live local-delta sidewalk add & erase!
            modules.Add(new JObject { ["id"] = "delta-door2", ["type"] = "door", ["x"] = 2, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["w"] = 2, ["cfg"] = new JObject { ["variant"] = "steel-2" } });
            modules.Add(new JObject { ["id"] = "delta-bench", ["type"] = "bench", ["x"] = 5, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["w"] = 1, ["cfg"] = new JObject { ["variant"] = "steel-1" } });
            modules.Add(new JObject { ["id"] = "delta-tree", ["type"] = "tree", ["x"] = 7, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["cfg"] = new JObject() });
            modules.Add(new JObject { ["id"] = "delta-pillar", ["type"] = "pillar", ["x"] = 9, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["cfg"] = new JObject { ["size"] = "slim", ["height"] = 4 } });
            modules.Add(new JObject { ["id"] = "delta-booth", ["type"] = "booth", ["x"] = 11, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["w"] = 3, ["h"] = 3, ["cfg"] = new JObject { ["kind"] = "ticket", ["front"] = 0 } });
            modules.Add(new JObject { ["id"] = "delta-fmark", ["type"] = "floor-mark", ["x"] = 15, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["cfg"] = new JObject { ["variant"] = "boarding" } });
            modules.Add(new JObject { ["id"] = "delta-exit", ["type"] = "exit", ["x"] = 17, ["y"] = 10, ["z"] = 0, ["rot"] = 0, ["cfg"] = new JObject { ["name"] = "B", ["style"] = "virtual" } });

            var host = CreateHost(out var hostObj, out var camObj);
            try {
                var opened = host.OpenDocument(BuildSaveJson(cells, modules, new JArray()), "file");
                Assert.IsTrue(opened.Accepted, "OpenDocument failed: " + opened);
                var world = host.Coordinator.World;

                // 1. Verify batched outdoor & equipment instances rise +0.10 m on sidewalk.
                Assert.IsTrue(TryMeasureModuleDocumentBounds(world, "tree-on-0", out var treeOn));
                Assert.IsTrue(TryMeasureModuleDocumentBounds(world, "tree-off-0", out var treeOff));
                Assert.AreEqual(0.10, treeOn.Z0 - treeOff.Z0, 0.01, "batched tree on sidewalk rises +0.10 m");

                Assert.IsTrue(TryMeasureModuleDocumentBounds(world, "bench-on-0", out var benchOn));
                Assert.IsTrue(TryMeasureModuleDocumentBounds(world, "bench-off-0", out var benchOff));
                Assert.AreEqual(0.10, benchOn.Z0 - benchOff.Z0, 0.01, "batched bench on sidewalk rises +0.10 m");

                // 2. Measure initial elevation of every local-delta target before paving y = 10.
                var deltaIds = new[] { "delta-door2", "delta-bench", "delta-tree", "delta-pillar", "delta-booth", "delta-fmark", "delta-exit" };
                var beforeZ0 = new Dictionary<string, double>(StringComparer.Ordinal);
                foreach (var id in deltaIds) {
                    Assert.IsTrue(TryMeasureModuleDocumentBounds(world, id, out var b), "Missing initial bounds for " + id);
                    beforeZ0[id] = b.Z0;
                }

                // 3. Lay sidewalk tiles under every target via live local-delta patch (no full world rebuild).
                var addPatch = new StationCellPatch();
                var addedSurfaceIds = new List<string>();
                foreach (int sx in new[] { 2, 5, 7, 9, 11, 15, 17 }) {
                    var sid = "sw-delta-" + sx;
                    addedSurfaceIds.Add(sid);
                    addPatch.AddModule(new StationEditDraft { Id = sid, Type = "sidewalk", X = sx, Y = 10, Z = 0, Rotation = 0 });
                }
                Assert.IsTrue(StationEditSession.TryApplyCells(host, addPatch, "surface", null, out _, out var addCode),
                    "Local sidewalk add failed: " + addCode);
                Assert.AreSame(world, host.Coordinator.World, "sidewalk add must retain StationWorldView via local delta");

                foreach (var id in deltaIds) {
                    Assert.IsTrue(TryMeasureModuleDocumentBounds(world, id, out var lifted), "Missing lifted bounds for " + id);
                    Assert.AreEqual(beforeZ0[id] + 0.10, lifted.Z0, 0.01, id + " must lift +0.10 m after local sidewalk add");
                }

                // 4. Erase those sidewalk tiles via live local-delta patch and verify everything drops back cleanly.
                var removePatch = new StationCellPatch();
                foreach (var sid in addedSurfaceIds) removePatch.RemoveModuleIds.Add(sid);
                Assert.IsTrue(StationEditSession.TryApplyCells(host, removePatch, "surface", null, out _, out var delCode),
                    "Local sidewalk remove failed: " + delCode);
                Assert.AreSame(world, host.Coordinator.World, "sidewalk remove must retain StationWorldView via local delta");

                foreach (var id in deltaIds) {
                    Assert.IsTrue(TryMeasureModuleDocumentBounds(world, id, out var restored), "Missing restored bounds for " + id);
                    Assert.AreEqual(beforeZ0[id], restored.Z0, 0.01, id + " must return to base elevation after local sidewalk remove");
                }
            } finally {
                if (camObj != null) UnityEngine.Object.DestroyImmediate(camObj);
                if (hostObj != null) UnityEngine.Object.DestroyImmediate(hostObj);
                ResetEditStatics();
            }
        }
