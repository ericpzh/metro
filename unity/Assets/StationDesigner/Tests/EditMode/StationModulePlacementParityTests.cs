        static StationEditDraft DraftFromRecord(StationModuleRecord rec) {
            var draft = new StationEditDraft {
                Id = "preview-" + rec.Id,
                Type = rec.Type,
                X = rec.X,
                Y = rec.Y,
                Z = rec.Z,
                Rotation = rec.Rotation,
                Width = rec.Width,
                Depth = rec.Depth,
                Height = rec.Height,
                PanelHeight = rec.PanelHeight,
                CeilingAnchored = rec.CeilingAnchored,
                From = rec.From,
                To = rec.To,
            };
            if (!string.IsNullOrEmpty(rec.RawJson)) {
                var parsed = JObject.Parse(rec.RawJson);
                if (parsed["cfg"] is JObject cfgObj) {
                    foreach (var prop in cfgObj.Properties()) {
                        if (prop.Value.Type == JTokenType.String) draft.Set(prop.Name, (string)prop.Value);
                        else draft.SetJson(prop.Name, prop.Value.ToString(Formatting.None));
                    }
                }
            }
            return draft;
        }

